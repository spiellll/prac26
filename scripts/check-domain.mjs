import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const load=async p=>import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(readFileSync(p,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText).toString('base64'));
const f=await load('lib/fitness.ts');
const base={id:'test',kind:'workout',date:'2026-09-20',createdAt:'2026-09-20T10:00:00Z',title:'Test',text:'',value:null,cycleIndex:3};
const set={reps:8,weight:60,warmup:false,effort:'hard'};
const exercise={name:'Присед',groups:['legs'],sets:[{...set},{...set},{...set}]};
const entries=[{...base,exercises:[exercise,{...exercise,sets:[{...set,warmup:true}]}]}];
const stat=(es=entries,day='2026-09-20',period=30)=>f.muscleStats(es,period,day).find(g=>g.id==='legs');
assert.equal(stat().sets,3,'Warmup must not count');
assert.equal(stat(entries,'2026-09-25',3).sets,0,'Historical period filter');
assert.equal(stat(entries,'2026-09-25',3).load,stat(entries,'2026-09-25',30).load,'Current index independent of history filter');
assert.ok(stat(entries,'2026-09-27').load<stat().load,'Index decays');
assert.equal(stat(entries,'2026-10-04').load,0,'Exactly zero at 14 days');
assert.equal(stat(entries,'2026-10-20').load,0,'Stays zero');
assert.equal(stat([{...entries[0],date:'2026-10-01'}],'2026-09-25').sets,0,'Future workouts excluded');
const fromSets=sets=>[{...base,exercises:[{...exercise,sets}]}];
const light=stat(fromSets(Array.from({length:3},()=>({...set,effort:'light'}))));
const heavy=stat(fromSets([{...set,effort:'max'}]));
assert.ok(light.load<heavy.load,'Three easy sets can count less than one maximal set');
assert.equal(stat(fromSets([{...set,weight:0}])).load,stat(fromSets([{...set,weight:100}])).load,'External kilograms alone do not measure relative effort');
assert.equal(stat(fromSets([{...set,effort:null}])).load,null,'Unknown effort never masquerades as zero load');
const partial=stat(fromSets([set,{...set,effort:null}]));
assert.equal(partial.unratedSets,1);assert.ok(f.loadLabel(partial).startsWith('≥'));
assert.equal(stat([{...base,exercises:[{...exercise,groups:[]}]}]).sets,0,'Unassigned group excluded');
assert.equal(stat(fromSets([{...set,warmup:true}])).load,0);
const multiple=f.normalizeEntry({...base,exercises:[{...exercise,groups:['legs','back','strength','legs']}]});
assert.deepEqual(multiple.exercises[0].groups,['legs','back','strength']);
const multiStats=f.muscleStats([multiple],30,'2026-09-20');
assert.equal(multiStats.find(g=>g.id==='legs').load,multiStats.find(g=>g.id==='back').load);
assert.ok(multiStats.find(g=>g.id==='strength').load>multiStats.find(g=>g.id==='legs').load,'Strength is independent of shared muscle allocation');
assert.equal(multiStats.find(g=>g.id==='strength').load,stat().load,'Adding strength tag does not take a share from muscles');
assert.equal(f.exerciseKey('  ПРИСЕД  '),f.exerciseKey('приседания'));
assert.equal(f.exerciseKey('Жим   лёжа'),f.exerciseKey('жим штанги лежа'));
assert.notEqual(f.exerciseKey('жим лежа'),f.exerciseKey('жим под наклоном'));
assert.equal(f.exerciseCatalog([{...base,exercises:[{...exercise,name:'присед'},{...exercise,name:'ПРИСЕДАНИЯ'}]}]).length,1);

const old=f.normalizeEntry({...base,exercises:[{name:'Присед',group:'legs',sets:4,reps:12,weight:62.5,warmup:false}]});
assert.deepEqual(old.exercises[0].groups,['legs']);assert.equal(old.exercises[0].sets.length,4);assert.equal(old.exercises[0].sets[3].weight,62.5);assert.equal(old.exercises[0].sets[0].effort,null);
assert.deepEqual(f.normalizeEntry(old),old,'Migration is idempotent');
assert.equal(f.nextCycle(entries,f.defaultProfile),0,'Cycle wraps across weeks');
const parsed=f.parseExercises('Присед 60 кг 3×10; подтягивания 10 кг 4 по 6');
assert.equal(parsed.length,2);assert.equal(parsed[1].sets[3].reps,6);assert.equal(parsed[0].sets[0].effort,null);
assert.equal(f.parseExercises('Сегодня вес тела 83 кг, не делал присед').length,0,'No invented exercises');
assert.equal(f.insights(entries,f.defaultProfile,'2026-09-25')[0].kind,'gap');
assert.equal(f.insights([],f.defaultProfile,'2026-09-25')[0].kind,'start');
assert.ok(f.diaryObservations(entries,f.defaultProfile,'2026-10-10').some(x=>x.id==='exercise-Присед'));
assert.notEqual(f.diaryRevision(entries,f.defaultProfile),f.diaryRevision(fromSets([{...set,weight:65}]),f.defaultProfile),'Advice becomes stale on edits');
assert.ok(f.chatGPTBrief(entries,f.defaultProfile,'2026-09-25').includes('Просушиться'));
console.log('Domain checks passed: per-set data, legacy conversion, effort, warmups, unknown groups, partial estimates, 14-day decay, dates, parsing, advice freshness.');
